import type { ComponentName } from './component-catalog'

export type PlaygroundFramework = 'webComponent' | 'react' | 'vue'

export interface PlaygroundSource {
  label: string
  language: string
  code: string
}

export interface PlaygroundSourceSet {
  webComponent?: PlaygroundSource
  react?: PlaygroundSource
  vue?: PlaygroundSource
}

interface PrimitiveSourceOptions {
  name: ComponentName
  title: string
  symbols: string[]
  webComponentMarkup: string
  frameworkMarkup: string
  vueMarkup?: string
}

function indent(value: string, spaces: number): string {
  const prefix = ' '.repeat(spaces)
  return value
    .split('\n')
    .map(line => `${prefix}${line}`)
    .join('\n')
}

function sourceInterpolation(expression: string): string {
  return ['$', '{', expression, '}'].join('')
}

function createPrimitiveSources(
  options: PrimitiveSourceOptions,
): PlaygroundSourceSet {
  const packageName = `@zeus-web/${options.name}`
  const symbols = options.symbols.join(', ')
  const vueMarkup = options.vueMarkup || options.frameworkMarkup

  return {
    webComponent: {
      label: 'Web Component',
      language: 'html',
      code: [
        '<script type="module">',
        `  import '${packageName}/wc/auto'`,
        '</script>',
        '',
        options.webComponentMarkup,
      ].join('\n'),
    },
    react: {
      label: 'React',
      language: 'tsx',
      code: [
        `import { ${symbols} } from '${packageName}/react'`,
        '',
        `export function ${options.title.replace(/\s/g, '')}Example() {`,
        '  return (',
        indent(options.frameworkMarkup, 4),
        '  )',
        '}',
      ].join('\n'),
    },
    vue: {
      label: 'Vue',
      language: 'vue',
      code: [
        '<script setup lang="ts">',
        `import { ${symbols} } from '${packageName}/vue'`,
        '</script>',
        '',
        '<template>',
        indent(vueMarkup, 2),
        '</template>',
      ].join('\n'),
    },
  }
}

