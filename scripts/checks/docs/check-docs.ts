function filePath(relativePath: string): string {
  return resolve(docsRoot, relativePath)
}

function checkFileExists(relativePath: string): string[] {
  const file = filePath(relativePath)
  if (!existsSync(file)) return [`Missing docs file: apps/docs/${relativePath}`]
  return []
}

function checkForbiddenPatterns(path: string, source: string): string[] {
  const errors: string[] = []

  for (const item of forbiddenPatterns) {
    if (source.includes(item.pattern)) {
      errors.push(`apps/docs/${path}: ${item.message}`)
    }
  }

  return errors
}

function checkRequiredContent(doc: RequiredDoc): string[] {
  const errors: string[] = []
  const source = readFileSync(filePath(doc.path), 'utf-8')

  for (const text of doc.mustContain) {
    if (!source.includes(text)) {
      errors.push(`apps/docs/${doc.path} must contain "${text}"`)
    }
  }

  errors.push(...checkForbiddenPatterns(doc.path, source))
  return errors
}

function checkVitePressConfig(): string[] {
  const configPath = filePath('.vitepress/config.ts')
  const siteDataPath = filePath('.vitepress/data/site.ts')
  const catalogPath = filePath('.vitepress/data/component-catalog.ts')
  const errors: string[] = []

  if (!existsSync(configPath)) return ['Missing apps/docs/.vitepress/config.ts']
  if (!existsSync(siteDataPath)) {
    return ['Missing apps/docs/.vitepress/data/site.ts']
  }
  if (!existsSync(catalogPath)) {
    return ['Missing apps/docs/.vitepress/data/component-catalog.ts']
  }

  const configSource = readFileSync(configPath, 'utf-8')
  const siteSource = readFileSync(siteDataPath, 'utf-8')
  const catalogSource = readFileSync(catalogPath, 'utf-8')

  for (const text of [
    "import { defineConfig } from 'vitepress'",
    "import { sidebar, topNav } from './data/site'",
    "logo: '/logo.svg'",
    'nav: topNav',
    'sidebar',
  ]) {
    if (!configSource.includes(text)) {
      errors.push(`VitePress config must contain "${text}"`)
    }
  }

  for (const route of [
    '/guide/getting-started',
    '/guide/usage-modes',
    '/guide/cli',
    '/guide/theming',
    '/guide/icons',
    '/components/',
    '/examples/react-vite',
    '/examples/next-app',
    '/examples/native-wc',
  ]) {
    if (!siteSource.includes(route)) {
      errors.push(`data/site.ts must contain route "${route}"`)
    }
  }

  for (const component of componentDocs) {
    if (!catalogSource.includes(component.route)) {
      errors.push(
        `component-catalog.ts must contain route "${component.route}"`,
      )
    }
  }

  for (const text of ['componentCatalog', 'componentCategories']) {
    if (!siteSource.includes(text)) {
      errors.push(`data/site.ts must derive navigation from "${text}"`)
    }
  }

  return errors
}

function checkDocsTheme(): string[] {
  return [
    '.vitepress/theme/index.ts',
    '.vitepress/theme/style.css',
    '.vitepress/theme/components/ComponentDirectory.vue',
    '.vitepress/data/component-catalog.ts',
    '.vitepress/data/site.ts',
  ].flatMap(file => checkFileExists(file))
}

function checkComponentDocsErrors(
  components: readonly ComponentCatalogItem[],
): string[] {
  const errors: string[] = []
  const registryComponents = getRegistryComponentNames()

  for (const component of components) {
    const relativePath = `components/${component.name}.md`
    const file = filePath(relativePath)

    if (!existsSync(file)) {
      errors.push(`Missing generated component doc: ${relativePath}`)
      continue
    }

    const source = readFileSync(file, 'utf-8')

    if (
      !source.includes(
        'This file is generated by scripts/commands/generate-docs.ts',
      )
    ) {
      errors.push(`${relativePath} must be generated`)
    }

    if (!source.includes(`${component.packageName}/react`)) {
      errors.push(
        `${relativePath} must document ${component.packageName}/react`,
      )
    }

    if (!source.includes(`${component.packageName}/wc/auto`)) {
      errors.push(
        `${relativePath} must document ${component.packageName}/wc/auto`,
      )
    }

    if (!source.includes(`${component.packageName}/vue`)) {
      errors.push(`${relativePath} must document ${component.packageName}/vue`)
    }

    const playgroundMarkup =
      component.name === 'data-grid'
        ? '<DataGridPlayground />'
        : `<ComponentPlayground name="${component.name}" />`

    if (
      !source.includes('## Playground') ||
      !source.includes(playgroundMarkup)
    ) {
      errors.push(
        `${relativePath} must embed its interactive Playground using "${playgroundMarkup}"`,
      )
    }

    if (source.includes('/playground/')) {
      errors.push(
        `${relativePath} must not link to a standalone Playground route`,
      )
    }

    if (component.packageGroup === 'advanced') {
      if (!source.includes(`pnpm add ${component.packageName}`)) {
        errors.push(
          `${relativePath} must document installing ${component.packageName}`,
        )
      }

      if (
        !source.includes('## Component family') ||
        !source.includes('## Methods')
      ) {
        errors.push(
          `${relativePath} must document its advanced component family and methods`,
        )
      }
    } else if (registryComponents.has(component.name)) {
      if (!source.includes(`zweb add ${component.name}`)) {
        errors.push(`${relativePath} must document zweb add ${component.name}`)
      }

      if (!source.includes(`@/components/ui/${component.name}`)) {
        errors.push(
          `${relativePath} must document @/components/ui/${component.name}`,
        )
      }

      if (!source.includes('Registry source: available.')) {
        errors.push(`${relativePath} must document registry availability`)
      }
    } else if (component.packageGroup === 'primitives') {
      if (!source.includes('Registry source: not available yet.')) {
        errors.push(`${relativePath} must document missing registry source`)
      }
    }

    errors.push(...checkForbiddenPatterns(relativePath, source))
  }

  return errors
}

function main(): void {
  const errors: string[] = []

  for (const doc of requiredDocs) {
    errors.push(...checkFileExists(doc.path))
    if (errors.length === 0 || existsSync(filePath(doc.path))) {
      errors.push(...checkRequiredContent(doc))
    }
  }

  errors.push(...checkDocsTheme())
  errors.push(...checkVitePressConfig())
  errors.push(...checkComponentDocsErrors(componentDocs))

  if (errors.length > 0) {
    console.error(pc.red('Docs check failed:'))

    for (const error of errors) console.error(`- ${error}`)

    process.exit(1)
  }

  console.log(pc.green('Docs check passed.'))
}

main()
